// 공통 토픽 체계 — 한국 기술사 ↔ 電験 1·2種
// ===================================================================
// 서브노트를 시험별로 따로 쓰지 않기 위한 단일 좌표계다.
//
// 왜 코드 체계가 필요한가
//   기술사는 「지중케이블 시스유기전압」, 電験은 「シース誘起電圧」으로 부른다.
//   같은 걸 다르게 부르니 자유 태그로는 절대 안 겹친다. 그래서 두 시험 사이에
//   중립적인 코드(D3)를 두고, 양쪽 기출이 그 코드를 가리키게 한다.
//
// 코드 읽는 법
//   A 기초이론 / B 전기기기 / C 발전 / D 송변전 / E 배전
//   F 계통해석·운용 / G 보호·접지 / H 전력품질 / I 제도·신기술
//
// 겹치지 않는 구간이 있다는 게 중요하다
//   jp 가 빈 배열  → 한국 전용 (I1 분산형전원 연계기준 등). 電験엔 아예 없다.
//   기술사 출제 0  → 電験 전용 (B4 직류기, B6 조명·전열 등)
//   이 둘을 한 서브노트에 섞으면 양쪽 다 흐려지므로 화면에서 갈라 보여준다.
//
// jpKeywords 의 역할
//   덴켄 1·2종 풀이 화면(denken12_answers.topic/keywords)에는 이미 자유 입력한
//   일본어 주제·키워드가 쌓여 있다. 코드를 소급해 달지 않아도 이 목록으로
//   문자열 매칭해서 「電験에서도 나온 토픽」을 즉시 집계한다.
//   나중에 denken12_answers.topic_code 를 채우면 그게 우선한다.

export type TopicGroup =
  | '기초이론' | '전기기기' | '발전' | '송변전' | '배전'
  | '계통해석' | '계통운용' | '보호' | '접지' | '전력품질' | '제도·신기술'

/** 電験 과목 — 1次 4과목 + 2次 2과목 */
export type JpSubject = '理論' | '電力' | '機械' | '法規' | '電力・管理' | '機械・制御'

export interface Topic {
  code: string
  group: TopicGroup
  name: string
  /** 이 토픽이 걸리는 電験 과목. 빈 배열이면 한국 전용 */
  jp: JpSubject[]
  /** denken12_answers 자유 텍스트와 매칭할 일본어 단서 */
  jpKeywords: string[]
  note?: string
}

