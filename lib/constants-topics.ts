// ===================================================================
// 서브노트를 시험별로 따로 쓰지 않기 위한 단일 좌표계다.
//
// 왜 이름을 키로 쓰는가
//   처음엔 A1·B1·G4 같은 코드를 썼는데, 그 코드에는 아무 정보가 없었다.
//   쓰려면 대조표를 외워야 하고 그건 도구가 아니라 숙제다.
//   그래서 코드를 버리고 이름 자체를 키로 삼는다. '변압기'가 곧 식별자다.
//   분류(group)와 電験 대응 과목(jp)은 별도 필드로 두고 화면에서 칩으로 보여준다.
//
// 왜 좌표계가 필요한가
//   기술사는 「지중케이블 시스유기전압」, 電験은 「シース誘起電圧」으로 부른다.
//   같은 걸 다르게 부르니 자유 태그로는 절대 안 겹친다. 양쪽 기출이 같은 키를
//   가리키게 해야 서브노트 한 장이 두 시험에서 쓰인다.
//
// 겹치지 않는 구간이 있다는 게 중요하다
//   jp 가 빈 배열  → 한국 전용 (분산형전원연계 등). 電験엔 아예 없다.
//   기술사 출제 0  → 電験 전용 (직류기, 조명전열 등)
//   이 둘을 한 서브노트에 섞으면 양쪽 다 흐려지므로 화면에서 갈라 보여준다.
//
// jpKeywords 의 역할
//   덴켄 1·2종 풀이 화면(denken12_answers.topic/keywords)에 자유 입력해 둔
//   일본어 주제·키워드를 소급 태깅 없이 끌어오기 위한 단서다.
//   denken12_answers.topic_code 를 채우면 그쪽이 우선한다.
//
// 범위에 대한 솔직한 한계
//   기술사는 연 3회라 15개년을 모아도 표본이 크지 않고, 출제 범위도 넓다.
//   여기서 하는 건 「경향 예측」이 아니라 「주제 분류와 출제 빈도 정리」다.
//   순위 하위권은 신호가 아니라 노이즈로 보는 게 맞다.

export type TopicGroup =
  | '기초이론' | '전기기기' | '발전' | '송변전' | '배전'
  | '계통해석' | '계통운용' | '보호' | '접지' | '전력품질' | '제도·신기술'

/** 電験 과목 — 1次 4과목 + 2次 2과목 */
export type JpSubject = '理論' | '電力' | '機械' | '法規' | '電力・管理' | '機械・制御'

export interface Topic {
  /** 키이자 표시명. 별도 코드가 없다 — 이 이름이 곧 식별자다 */
  key: string
  group: TopicGroup
  /** 화면에 쓰는 온전한 이름 (키보다 길 수 있다) */
  name: string
  /** 이 토픽이 걸리는 電験 과목. 빈 배열이면 한국 전용 */
  jp: JpSubject[]
  /** denken12_answers 자유 텍스트와 매칭할 일본어 단서 */
  jpKeywords: string[]
  note?: string
}

