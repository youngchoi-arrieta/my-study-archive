/**
 * 덴켄 자유 텍스트(topic + keywords)에서 토픽 코드를 추정한다.
 * denken12_answers.topic_code 가 채워져 있으면 그쪽이 우선이고,
 * 이건 소급 태깅 없이 기존 데이터를 살리기 위한 보조 경로다.
 */
export function guessTopicCodes(text: string): string[] {
  if (!text) return []
  const hay = text.toLowerCase()
  const hit: string[] = []
  for (const t of TOPICS) {
    if (t.jpKeywords.some(k => hay.includes(k.toLowerCase()))) hit.push(t.key)
  }
  return hit
}

