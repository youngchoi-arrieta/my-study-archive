// ── 논점 ────────────────────────────────────────────────────────────
// 대주제 43개는 「분류」지 「서브노트 작성 단위」가 아니다.
// 변압기 하나에 25문항이 걸리는데, 그 안에는 시험·정수 / 효율·손실 / 병렬운전 /
// 결선·각변위 / 냉각방식 / 보호가 다 들어 있다. "변압기 공부해라"로는 한 장을 못 쓴다.
//
// 그래서 태그를 두 단으로 쓴다:  대주제/논점   예) '변압기/병렬운전'
//   · 대주제는 이 파일의 TOPICS 에 있는 것만 쓴다 (電験 매칭이 이 단위로 걸린다)
//   · 논점은 자유 문자열이다. 미리 정한 목록이 아니라 기출에서 실제로 나온 것만 쌓인다.
//     새 논점이 필요하면 그냥 새로 쓰면 되고, 기존 목록은 화면에서 골라 쓴다.
//   · 논점 없이 대주제만 달아도 된다. 문항이 적은 대주제는 쪼갤 이유가 없다.
//
// 서브노트 한 장 = 태그 하나.

export interface Tag { topic: string; point: string | null; raw: string }

export function parseTag(raw: string): Tag {
  const key = resolveKey(raw)
  const i = key.indexOf('/')
  if (i < 0) return { topic: key, point: null, raw: key }
  return { topic: key.slice(0, i), point: key.slice(i + 1), raw: key }
}

export const makeTag = (topic: string, point?: string | null) =>
  point && point.trim() ? `${topic}/${point.trim()}` : topic

/** 화면 표기 — 논점이 있으면 논점을, 없으면 대주제를 제목으로 */
export const tagLabel = (raw: string) => {
  const t = parseTag(raw)
  return t.point ?? (TOPIC_MAP.get(t.topic)?.name ?? t.topic)
}

export const tagTopic = (raw: string) => TOPIC_MAP.get(parseTag(raw).topic)
